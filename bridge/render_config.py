"""Render LiteLLM config, clamp map, and provider profiles from the registry.

Inputs (single source of truth):
  registry/models.yaml     — auto-discovered facts (ctx / max_output / vision)
  registry/profiles.yaml   — hand-authored choices (tier -> model, aliases)

Outputs (all generated; safe to regenerate):
  bridge/config.generated.yaml   — LiteLLM model_list with model_info limits
  bridge/clamp_map.json          — {model: max_output} for the proxy clamp
  providers/<profile>.json.example — Claude Code profile with correct context

Usage:
  python3 render_config.py                 # render everything
  python3 render_config.py --check         # exit 1 if outputs are stale
"""
