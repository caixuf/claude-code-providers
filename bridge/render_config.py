def load_yaml(path: Path) -> dict:
    try:
        import yaml  # type: ignore
    except Exception as e:  # pragma: no cover
        sys.exit(f"pyyaml required (pip install pyyaml): {e}")
    if not path.is_file():
        sys.exit(f"missing {path}")
    return yaml.safe_load(path.read_text()) or {}


def index_models(doc: dict) -> dict:
    """(provider, name) -> model dict, plus provider meta."""
    models: dict[tuple[str, str], dict] = {}
    providers: dict[str, dict] = {}
    for p in doc.get("providers", []):
        providers[p["name"]] = p
        for m in p.get("models") or []:
            models[(p["name"], m["name"])] = dict(m, _from_registry=True)
    return models, providers


def litellm_model_string(provider: str, name: str, meta: dict) -> str:
    """Build the `model:` value LiteLLM passes upstream."""
    override = litellm_model_string_override(provider, name)
    if override:
        return override
    kind = meta.get("endpoint_kind", "openai")
    if kind == "anthropic":
        return f"anthropic/{name}"
    # ChatGPT OAuth is a LiteLLM-native provider: it owns both the endpoint and
    # the token store, so the id has to stay `chatgpt/<model>` — prefixing it
    # with `openai/` would send it to api.openai.com with no key.
    if kind == "chatgpt":
        return f"chatgpt/{name}"
    # OpenAI-compatible gateways: keep the upstream id verbatim, prefixed openai/
    if name.startswith(("openai/", "anthropic/", "github_copilot/", "openrouter/")):
        return name
    return f"openai/{name}"


def clamp_value(meta: dict) -> int | None:
    v = meta.get("max_output")
    return int(v) if isinstance(v, (int, float)) else None


def render_config(
    models: dict,
    providers: dict,
    profiles_doc: dict,
    emitted_names: dict[str, set[str]] | None = None,
) -> str:
    """Emit LiteLLM model_list.

    One entry per alias + one per exposed model, each carrying model_info with
    max_input_tokens / max_output_tokens / supports_vision so LiteLLM also
    knows the capability (belt-and-braces with the proxy clamp).

    ``emitted_names``, when given, is populated with {provider: {model_name}} for
    every entry actually written. That is what render_request_rules() needs: the
    proxy can only key a rule on a name the client can actually send, and two
    providers may share an upstream id (e.g. ``gpt-5.3-codex`` exists under both
    cmdc and codebuddy) — only the provider that won the entry may claim it.
    """
    lines = [
        "# GENERATED by bridge/render_config.py — DO NOT EDIT.",
        "# Source of truth: registry/models.yaml + registry/profiles.yaml",
        "# Regenerate:  ccp render",
        "",
        "model_list:",
    ]

    emitted: set[str] = set()
    # (model_name, upstream) pairs already written for a routing group. A group
    # is *supposed* to repeat one model_name across several upstreams — that is
    # what makes LiteLLM load-balance and cool down a member that 429s — so the
    # single-name guard above cannot apply to pool members.
    pool_pairs: set[tuple[str, str, str | None]] = set()
    # LiteLLM load-balances across deployments that share a model_name, so an
    # account suffix produces a *pool* for free — no custom router needed.
    # {provider -> {suffix: {auth_env: ...}}}
    accounts = profiles_doc.get("accounts") or {}

    def emit(
        model_name: str,
        provider: str,
        upstream: str,
        meta: dict,
        api_key_env: str | None = None,
        allow_duplicate: bool = False,
    ) -> None:
        key = model_name.strip().strip("'")
        if not allow_duplicate:
            if key in emitted:
                return
            emitted.add(key)
        elif (key, upstream, api_key_env) in pool_pairs:
            # A pool member may repeat the model_name (that is what makes
            # LiteLLM load-balance), but the same *deployment* twice is noise.
            # The credential is part of the identity: two accounts of one model
            # are two deployments, not one.
            return
        else:
            pool_pairs.add((key, upstream, api_key_env))
        if emitted_names is not None:
            emitted_names.setdefault(provider, set()).add(key)
        lines.append(f"  - model_name: {model_name}")
        lines.append("    litellm_params:")
        lines.append(f"      model: {upstream}")
        pmeta = providers.get(provider, {})
        api_base = pmeta.get("api_base")
        override = _env_api_base(provider, providers)
        if override:
            api_base = override
        if api_base:
            lines.append(f"      api_base: {api_base}")
        # Headers every request to this provider must carry. They belong to
        # the deployment, not to the model.
        eh = pmeta.get("extra_headers") or {}
        if eh:
            lines.append("      extra_headers:")
            for k in eh:
                lines.append(f"        {k}: {eh[k]}")
        # key from env (proxy.env supplies it) — never inline secrets.
        # Copilot authenticates via its own token store, so no api_key.
        auth_env = api_key_env or pmeta.get("auth_env")
        if auth_env and provider != "copilot":
            lines.append(f"      api_key: os.environ/{auth_env}")
        info = []
        if isinstance(meta.get("ctx"), (int, float)):
            info.append(f"        max_input_tokens: {int(meta['ctx'])}")
        cv = clamp_value(meta)
        if cv is not None:
            info.append(f"        max_output_tokens: {cv}")
        if meta.get("vision") is not None:
            info.append(f"        supports_vision: {'true' if meta['vision'] else 'false'}")
        if info:
            lines.append("      model_info:")
            lines.extend(info)
        lines.append("")

    def emit_family(base: str, provider: str, upstream: str, meta: dict) -> None:
        """Emit one model name in every spelling the client may send.

        Both the bare name and the ``[1m]``-bracketed form are emitted, because
        ``ccp -m <name>`` sends the bare one while Claude Code appends ``[1m]``
        to a 1M-context model (the proxy strips it before forwarding).

        Every account of the provider becomes another deployment of the *same*
        names, differing only in the credential env var. That is what makes a
        pool: LiteLLM spreads load across them and cools down one that answers
        429, so an exhausted account is skipped without the client knowing it
        exists. Suffixing the name instead (``codebuddy-a2``) would produce no
        failover at all — the client would have to know which to try.
        """
        bracketed = (meta.get("ctx") or 0) >= 1_000_000
        pacc = accounts.get(provider) or {}
        envs: list[str | None] = [None]
        if isinstance(pacc, dict):
            for spec in pacc.values():
                if isinstance(spec, dict) and spec.get("auth_env"):
                    envs.append(spec["auth_env"])
        for env in envs:
            emit(base, provider, upstream, meta, env, allow_duplicate=True)
            if bracketed:
                emit(f"'{base}[1m]'", provider, upstream, meta, env, allow_duplicate=True)

    def emit_pool(group: str, provider: str, upstream: str, meta: dict, suffix: str = "") -> None:
        """One deployment of a routing group, under the group's model_name.

        The account ``suffix`` selects a credential and must NOT change the
        model_name: every (member, account) pair is one deployment of the same
        group, which is what lets LiteLLM spread load over the whole matrix.
        Duplicate model_names are intentional here, so these bypass the
        single-name guard.
        """
        pacc = accounts.get(provider) or {}
        env = None
        if suffix and isinstance(pacc, dict):
            spec = pacc.get(suffix) or {}
            env = spec.get("auth_env")
        emit(group, provider, upstream, meta, env, allow_duplicate=True)

    # 1. curated aliases
    alias_models: dict[str, int] = {}
    for alias, spec in (profiles_doc.get("aliases") or {}).items():
        pname = spec["provider"]
        mname = spec["model"]
        meta = models.get((pname, mname))
        if meta is None:
            meta = synth_meta(profiles_doc, pname, mname)
            if meta.get("ctx") is None and not _np_providers(profiles_doc).get(pname):
                print(f"  ! alias {alias}: model {mname} not in registry", file=sys.stderr)
                continue
        upstream = litellm_model_string(pname, mname, meta)
        emit_family(alias, pname, upstream, meta)
        alias_models[alias] = clamp_value(meta) or 0

    # 1b. every model referenced by a profile's tiers (so copilot, whose
    #     provider isn't auto-discovered, still gets config entries).
    for profile, spec in (profiles_doc.get("profiles") or {}).items():
        pname = spec["provider"]
        for tier, tspec in (spec.get("tiers") or {}).items():
            mname = tspec["model"]
            meta = models.get((pname, mname))
            if meta is None:
                # non-discovered provider (e.g. copilot): synthesise from override
                meta = synth_meta(profiles_doc, pname, mname)
            upstream = litellm_model_string(pname, mname, meta)
            # config key = the name Claude Code will send (alias if any)
            key = litellm_key_for(profiles_doc, pname, mname)
            emit_family(key, pname, upstream, meta)

    # 2. individually exposed models (reachable via `ccp -m <name>`)
    for mname in profiles_doc.get("expose_models") or []:
        hit = next((key for key, m in models.items() if m["name"] == mname), None)
        if not hit:
            print(f"  ! expose_models: {mname} not discovered", file=sys.stderr)
            continue
        pname, _ = hit
        emit_family(mname, pname, litellm_model_string(pname, mname, models[hit]), models[hit])

    # 3. Routing groups. A group is ONE model_name with one deployment per
    #    (member, account) pair. That is what lets LiteLLM spread load across
    #    the whole matrix and cool down whichever member or account answers
    #    429 — the client only ever names the group. Members are NOT split into
    #    per-account names here: a `daily-a2` the client must know to try would
    #    defeat the point.
    for gname, gspec in (profiles_doc.get("groups") or {}).items():
        members = [m for m in (gspec.get("members") or []) if m]
        if not members:
            print(f"  ! group {gname}: no members", file=sys.stderr)
            continue
        for gmember in members:
            gprov, gmodel = _split_member(profiles_doc, models, gmember)
            if gprov is None:
                print(f"  ! group {gname}: cannot resolve member {gmember}", file=sys.stderr)
                continue
            gmeta = models.get((gprov, gmodel)) or synth_meta(profiles_doc, gprov, gmodel)
            gup = litellm_model_string(gprov, gmodel, gmeta)
            emit_pool(gname, gprov, gup, gmeta)
            # every account of the member joins the same pool
            pacc = accounts.get(gprov) or {}
            if isinstance(pacc, dict):
                for suffix in pacc:
                    emit_pool(gname, gprov, gup, gmeta, suffix)

    # 4. router_settings: per-group strategies + cross-name fallbacks
    lines += render_router_settings(profiles_doc)

    lines += [
        "",
        "litellm_settings:",
        "  drop_params: true",
        "",
        "general_settings:",
        "  master_key: sk-cmdc-litellm-local",
    ]
    return "\n".join(lines) + "\n"


def _split_member(profiles_doc: dict, models: dict, member: str) -> tuple[str | None, str]:
    """Resolve a group member to (provider, model).

    A member may be written as an alias, as a bare registry model id, or as
    ``provider/model``. Returns ``(None, member)`` when nothing resolves, so the
    caller reports it instead of emitting a deployment that 404s.
    """
    alias = (profiles_doc.get("aliases") or {}).get(member)
    if alias:
        return alias["provider"], alias["model"]
    for (pname, mname) in models:
        if mname == member:
            return pname, mname
    if "/" in member:
        pname, mname = member.split("/", 1)
        return pname, mname
    return None, member


def render_router_settings(profiles_doc: dict) -> list[str]:
    """Emit LiteLLM ``router_settings`` for the curated groups.

    ``routing_groups`` gives a group name its own routing strategy (the group
    itself is just several deployments sharing that name, emitted above).
    ``fallbacks`` chains a name to the next one once every deployment in it has
    failed or is cooling down. Both are native LiteLLM; ccp adds no router.
    """
    groups = profiles_doc.get("groups") or {}
    rg: list[str] = []
    fb: list[str] = []
    for gname, gspec in groups.items():
        if not (gspec.get("members") or []):
            continue
        strategy = gspec.get("routing_strategy")
        if strategy:
            rg.append(f"  - group_name: {gname}")
            # The group's deployments all share the group name, so the group
            # claims exactly that one model_name.
            rg.append("    models:")
            rg.append(f"      - {gname}")
            rg.append(f"    routing_strategy: {strategy}")
            args = gspec.get("routing_strategy_args")
            if isinstance(args, dict) and args:
                rg.append("    routing_strategy_args:")
                for k, v in args.items():
                    rg.append(f"      {k}: {v}")
        for target in gspec.get("fallback") or []:
            fb.append(f"  - {gname}: [{target}]")

    out: list[str] = []
    if fb:
        out.append("")
        out.append("router_settings:")
        out.append("  fallbacks:")
        out.extend(fb)
    if rg:
        if not out:
            out.append("")
            out.append("router_settings:")
        out.append("  routing_groups:")
        out.extend(rg)
    return out


def render_clamp(models: dict, providers: dict, profiles_doc: dict) -> dict:
    """Flat map {model name (and alias) -> max_output}.

    Includes bracket variants and both the alias and the bare upstream id so
    the proxy resolves whichever spelling Claude Code sends.
    """
    out: dict[str, int] = {}

    def meta_for(pname: str, mname: str) -> dict:
        """Registry metadata, falling back to profiles.yaml model_defaults.

        Without the fallback a non-discovered provider (copilot) contributed no
        clamp entry at all, so its models were clamped by ``__fallback__``
        instead of by their real cap.
        """
        meta = models.get((pname, mname))
        return meta if meta is not None else synth_meta(profiles_doc, pname, mname)

    for alias, spec in (profiles_doc.get("aliases") or {}).items():
        cv = clamp_value(meta_for(spec["provider"], spec["model"]))
        if cv:
            out[alias] = cv
            out[alias + "[1m]"] = cv
    for mname in profiles_doc.get("expose_models") or []:
        hit = next((m for (p, m) in models.items() if m["name"] == mname), None)
        if not hit:
            continue
        cv = clamp_value(hit)
        if cv:
            out[mname] = cv
            out[mname + "[1m]"] = cv
    # every model a profile pins to a tier, so tiers without an alias still clamp
    for spec in (profiles_doc.get("profiles") or {}).values():
        pname = spec.get("provider", "")
        for tspec in (spec.get("tiers") or {}).values():
            mname = tspec.get("model")
            if not mname:
                continue
            cv = clamp_value(meta_for(pname, mname))
            if cv:
                out.setdefault(mname, cv)
                out.setdefault(mname + "[1m]", cv)
    # every discovered model, so unknown ids still clamp correctly
    for (pname, name), meta in models.items():
        cv = clamp_value(meta)
        if cv:
            out.setdefault(name, cv)
    # explicit fallback for models not in the map: use the most common cap
    # (the bridged gateways all share one), NOT the global minimum, which can
    # be a tiny obscure model and would over-truncate.
    if out:
        from collections import Counter

        out["__fallback__"] = Counter(out.values()).most_common(1)[0][0]
    return out


def _np_providers(profiles_doc: dict) -> dict:
    """Non-discovered provider definitions (copilot, *-native) from profiles.yaml."""
    return profiles_doc.get("providers") or {}


def synth_meta(profiles_doc: dict, pname: str, mname: str) -> dict:
    """Metadata for a model not present in the registry (e.g. github_copilot).

    Looks in profiles.yaml ``providers.<pname>.model_defaults`` for a substring
    match, so copilot / native models get sane ctx/output/vision numbers.
    """
    pdef = _np_providers(profiles_doc).get(pname) or {}
    for pat, meta in (pdef.get("model_defaults") or {}).items():
        if pat in mname:
            return dict(meta, _from_registry=False, endpoint_kind=pdef.get("endpoint_kind"))
    return {"ctx": None, "max_output": None, "vision": None, "_from_registry": False}


def render_request_rules(profiles_doc: dict, emitted_by_provider: dict[str, set[str]]) -> dict:
    """Expand profiles.yaml ``request_rules`` (provider -> rewrite) into model names.

    The proxy sits in front of LiteLLM, so the only thing it can key on is the
    model name the client sent. That name is one of the entries
    ``render_config`` actually emitted for the provider — an alias, a tier's
    model, or an exposed id — which is exactly what ``emitted_by_provider``
    records. Names are compared after ``norm_model_key`` in the proxy, so the
    ``[1m]`` variants are already covered.
    """
    declared = profiles_doc.get("request_rules") or {}
    rules: dict[str, list[str]] = {}
    for rule, provs in declared.items():
        names: set[str] = set()
        for pname in set(provs or []):
            names |= set(emitted_by_provider.get(pname, ()))
        rules[rule] = sorted(names)
    return rules


def render_media_rules(
    models: dict, profiles_doc: dict, emitted_by_provider: dict[str, set[str]]
) -> list[str]:
    """Names of emitted models the registry records as text-only.

    Derived, never hand-written: ``vision`` is a *discovered* fact in
    ``registry/models.yaml``, so a model that gains or loses image input changes
    this list on the next ``ccp render`` with nobody editing a second place. A
    hand-kept list is the failure this replaces — it would have named the Qianfan
    flash id that broke, and missed whichever id the next key serves.

    Only an explicit ``vision: false`` qualifies. ``vision: null`` means the
    probe never established the capability, and downgrading on a guess would
    silently discard a screenshot on a model that could have read it; an unknown
    model therefore keeps its pixels and, if it cannot take them, fails loudly
    instead of degenerating quietly.
    """
    aliases = profiles_doc.get("aliases") or {}

    def vision_of(pname: str, name: str):
        spec = aliases.get(name)
        if isinstance(spec, dict) and spec.get("provider") == pname:
            return (models.get((pname, spec.get("model"))) or {}).get("vision")
        for candidate in (name, name.split("[", 1)[0]):
            meta = models.get((pname, candidate))
            if meta is not None:
                return meta.get("vision")
        return None

    text_only: set[str] = set()
    for pname, names in (emitted_by_provider or {}).items():
        for name in names:
            if vision_of(pname, name) is False:
                text_only.add(name)
    return sorted(text_only)


def litellm_model_string_override(pname: str, mname: str, profiles_doc: dict | None = None) -> str | None:
    """LiteLLM model string for non-registry providers (copilot uses its native
    ``github_copilot/`` prefix and must NOT get an ``openai/`` prefix)."""
    if pname == "cline":
        # Cline Pass is a flat subscription namespace: the request model MUST be
        # ``cline-pass/<model>`` (org segment dropped) or it silently bills
        # pay-as-you-go credits instead of the pass. Documented in
        # bridge/config.example.yaml; dropping it here re-broke that (402).
        return f"openai/cline-pass/{mname.rsplit('/', 1)[-1]}"
    if pname in ("codebuddy", "workbuddy"):
        # Retired with the provider (docs/archived-providers.md), kept so an
        # old registry still renders the prefix it expects rather than falling
        # through to ``openai/`` and hitting the Responses API. Both gateways
        # serve /chat/completions only under /v2 and 404 the whole /v1/* and
        # /responses surface; ``hosted_vllm/`` is LiteLLM's generic
        # OpenAI-compatible prefix and keeps the chat/completions builder per
        # deployment.
        return f"hosted_vllm/{mname}"
    if pname == "codex":
        # The local Codex gateway has an Anthropic front door (:56895/v1/messages,
        # which is what the native profile uses) and, on the same base URL, an
        # OpenAI chat/completions one. It does NOT have an OpenAI *Responses*
        # front door, whatever /v1/responses appears to return: forwarded there,
        # a request comes back as "unsupported_endpoint ... not supported by the
        # native Responses service". That is exactly the path an ``anthropic/``
        # deployment takes when reached through LiteLLM's own /v1/messages, so
        # the bridged copy would 404 for a model the direct one answers in 2s.
        # ``hosted_vllm/`` is LiteLLM's generic OpenAI-compatible prefix: it keeps
        # the chat/completions builder per deployment, the same opt-out
        # CodeBuddy needed, without touching any other provider.
        return f"hosted_vllm/{mname}"
    if mname.startswith(("github_copilot/", "anthropic/", "openai/", "openrouter/")):
        return mname
    if pname == "copilot":
        return f"github_copilot/{mname}"
    return None


def _alias_index(profiles_doc: dict) -> dict[tuple[str, str], str]:
    """(provider, model) -> alias, for turning ugly upstream ids into short names."""
    out = {}
    for alias, spec in (profiles_doc.get("aliases") or {}).items():
        out[(spec["provider"], spec["model"])] = alias
    return out


def litellm_key_for(profiles_doc: dict, pname: str, mname: str) -> str:
    """The model_name LiteLLM is given for one (provider, model).

    A deployment is named by its curated alias when there is one and by the bare
    registry id otherwise (``render_config`` §1b), and a client can only reach a
    deployment by that name. Anything that has to *call* the bridge — ``ccp -m``,
    and the Hermes config — must resolve the same way, or it names a model the
    proxy never emitted and gets a 400.
    """
    for alias, spec in (profiles_doc.get("aliases") or {}).items():
        if spec.get("provider") == pname and spec.get("model") == mname:
            return alias
    return mname


def render_profile(
    profile: str,
    spec: dict,
    models: dict,
    providers: dict,
    alias_idx: dict | None = None,
    profiles_doc: dict | None = None,
) -> str:
    pname = spec["provider"]
    tiers = spec["tiers"]
    alias_idx = alias_idx or {}
    profiles_doc = profiles_doc or {}

    # A native profile talks to the provider directly: there is no bridge to
    # translate the name it sends, so it must send the UPSTREAM model id and
    # never the alias or the `[1m]` suffix. Both are ccp inventions that exist
    # only because the watchdog strips them on the bridged path — a native
    # endpoint answers `model "opendesign[1m]" not found` (verified against
    # OpenDesign and the same for any strict Anthropic endpoint).
    # deepseek/minimax only appeared to work because their tiers happen to use
    # ids with no alias; those profiles were silently one rename away from
    # breaking.
    native = spec.get("native", False)

    def claude_name(mname: str) -> str:
        """Prefer the friendly alias over the raw upstream id.

        Bridged only: a native endpoint has no idea what an alias is.
        """
        if native:
            return mname
        a = alias_idx.get((pname, mname))
        return a if a else mname

    # resolve each tier to (display name, ctx, bracketed)
    resolved = {}
    for tier in TIER_ORDER:
        if tier not in tiers:
            continue
        mname = tiers[tier]["model"]
        meta = models.get((pname, mname))
        if meta is None:
            # scan any provider for the name (native / cross-provider)
            hit = next((key for key, m in models.items() if m["name"] == mname), None)
            meta = models[hit] if hit else None
        if meta is None:
            # non-discovered provider (copilot, *-native): provider_descs
            meta = synth_meta(profiles_doc, pname, mname)
        display = claude_name(mname)
        ctx = (meta or {}).get("ctx") if meta else None
        resolved[tier] = {
            "display": display,
            "ctx": ctx,
            # the bracketed spelling is a bridged-path convention only
            "bracketed": (not native) and (ctx or 0) >= 1_000_000,
        }

    primary = spec.get("primary_tier", "default")
    pctx = resolved.get(primary, {}).get("ctx") or 200000
    ctx_str = str(int(pctx))

    def fmt(tier: str) -> str:
        r = resolved.get(tier)
        if not r:
            return resolved.get("default", {}).get("display", "")
        return r["display"] + ("[1m]" if r["bracketed"] else "")

    auth = "sk-cmdc-litellm-local" if not native else "YOUR_" + spec["provider"].split("-")[0].upper() + "_API_KEY"
    env = {
        "ANTHROPIC_AUTH_TOKEN": auth,
        "ANTHROPIC_BASE_URL": _base_url(pname, providers, native),
        "ANTHROPIC_MODEL": fmt(primary),
        "ANTHROPIC_DEFAULT_OPUS_MODEL": fmt("opus"),
        "ANTHROPIC_DEFAULT_FABLE_MODEL": fmt("fable"),
        "ANTHROPIC_DEFAULT_SONNET_MODEL": fmt("sonnet"),
        "ANTHROPIC_DEFAULT_HAIKU_MODEL": fmt("haiku"),
        "ANTHROPIC_SMALL_FAST_MODEL": fmt("haiku"),
        "CLAUDE_CODE_MAX_CONTEXT_TOKENS": ctx_str,
        "CLAUDE_CODE_AUTO_COMPACT_WINDOW": ctx_str,
    }
    obj = {
        "env": env,
        "permissions": {"defaultMode": "bypassPermissions"},
        "model": fmt(primary),
        "autoUpdatesChannel": "stable",
        "skipDangerousModePermissionPrompt": True,
        "theme": "dark",
    }
    return json.dumps(obj, indent=2) + "\n"


def _base_url(pname: str, providers: dict, native: bool) -> str:
    """Native profiles point straight at the provider; bridged ones use :4000."""
    if native:
        pmeta = providers.get(pname, {})
        if pmeta.get("api_base"):
            return pmeta["api_base"]
    return "http://127.0.0.1:4000"


def _env_api_base(pname: str, providers: dict) -> str | None:
    """A host the account's own login chose, if the secrets file names one.

    A subscription can run two gateways (an international site and a CN one)
    and a session is valid at exactly the one it was issued by, so the host
    belongs to the *account*, not to the provider. The importer writes the
    login's own base into proxy.env as `<PROVIDER>_API_BASE`; this reads it
    back, so a CN account is rendered against the CN gateway instead of being
    refused with a bare 401 that looks like an expired login.

    Only a host is read here — never a secret — so baking it into the
    generated config is safe.
    """
    pmeta = providers.get(pname) or {}
    if not pmeta.get("api_base"):
        return None
    env_file = Path(os.path.expanduser("~/.config/litellm/proxy.env"))
    if not env_file.is_file():
        return None
    want = f"{pname.upper()}_API_BASE="
    try:
        for line in env_file.read_text().splitlines():
            if line.startswith(want):
                val = line.split("=", 1)[1].strip().strip("'\"")
                return val or None
    except Exception:
        return None
    return None


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="verify outputs are up to date")
    args = ap.parse_args()

    models_doc = load_yaml(MODELS_YAML)
    profiles_doc = load_yaml(PROFILES_YAML)
    models, providers = index_models(models_doc)
    # register non-discovered providers (copilot, *-native) so emit() knows their shape
    for pname, pmeta in _np_providers(profiles_doc).items():
        providers.setdefault(pname, {"auth_env": None, "api_base": None, **pmeta})

    emitted_by_provider: dict[str, set[str]] = {}
    config_text = render_config(models, providers, profiles_doc, emitted_by_provider)
    clamp = render_clamp(models, providers, profiles_doc)
    clamp_text = json.dumps(clamp, indent=2, sort_keys=True) + "\n"
    rules = render_request_rules(profiles_doc, emitted_by_provider)
    # `media_downgrade` is derived from the registry, not declared in
    # profiles.yaml: the capability is a discovered fact, so the rule set has to
    # follow it rather than be a second place to keep in sync.
    rules["media_downgrade"] = render_media_rules(models, profiles_doc, emitted_by_provider)
    rules_text = json.dumps(rules, indent=2, sort_keys=True) + "\n"

    profile_texts = {}
    alias_idx = _alias_index(profiles_doc)
    for profile, spec in (profiles_doc.get("profiles") or {}).items():
        profile_texts[profile] = render_profile(profile, spec, models, providers, alias_idx, profiles_doc)

    if args.check:
        stale = []
        if not CONFIG_OUT.is_file() or CONFIG_OUT.read_text() != config_text:
            stale.append(str(CONFIG_OUT))
        if not CLAMP_OUT.is_file() or CLAMP_OUT.read_text() != clamp_text:
            stale.append(str(CLAMP_OUT))
        if not RULES_OUT.is_file() or RULES_OUT.read_text() != rules_text:
            stale.append(str(RULES_OUT))
        for profile, text in profile_texts.items():
            fp = PROFILES_OUT / f"{profile}.json.example"
            if not fp.is_file() or fp.read_text() != text:
                stale.append(str(fp))
        if stale:
            print("Stale outputs (run `ccp render`):")
            for s in stale:
                print("  ", s)
            sys.exit(1)
        print("All rendered outputs up to date.")
        return

    CONFIG_OUT.write_text(config_text)
    CLAMP_OUT.write_text(clamp_text)
    RULES_OUT.write_text(rules_text)
    PROFILES_OUT.mkdir(parents=True, exist_ok=True)
    for profile, text in profile_texts.items():
        (PROFILES_OUT / f"{profile}.json.example").write_text(text)

    print(f"Rendered {len(clamp)} clamp entries -> {CLAMP_OUT.name}")
    print(f"Rendered config -> {CONFIG_OUT.name}")
    if rules:
        print("Rendered request rules -> " + RULES_OUT.name + " (" + ", ".join(f"{k}: {len(v)}" for k, v in sorted(rules.items())) + ")")
    print(f"Rendered {len(profile_texts)} profiles -> providers/*.json.example")


if __name__ == "__main__":
    main()
